def _module(name: str) -> str:
    import re

    return re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_") or "app"


def _have(req: str) -> bool:
    return any(shutil.which(x) for x in req.split("|"))


def create(dest: Path, stack: str, name: str = None, prove: bool = True) -> dict:
    if stack not in STACKS:
        raise RatchetError(f"unknown stack {stack}; known: {', '.join(STACKS)} (or follow `ratchet brief new`)")
    if dest.exists() and any(dest.iterdir()):
        raise RatchetError(f"{dest} exists and isn't empty")
    spec = STACKS[stack]
    name = name or dest.name
    module = _module(name)
    dest.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", "-b", "main"], cwd=str(dest), check=True)
    for rel, content in spec["files"].items():
        rel = rel.replace("{{module}}", module).replace(".ratchet-kit/", ".ratchet/")
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content.replace("{{name}}", name).replace("{{module}}", module))
        if rel.endswith(".sh"):
            p.chmod(0o755)
    (dest / "README.md").write_text(f"# {name}\n\n{spec['describe']}. Created with `ratchet new {stack}`: "
                                    "every change goes through ratchet's verified cycle (see AGENTS.md).\n")
    plan = generate.plan(dest)
    info = generate.write(dest, plan)
    h = harness.load(dest)
    if spec["exercises"] and h["products"]:
        h["products"][0]["exercises"] = spec["exercises"]
        harness.save(dest, h)
    missing = [r for r in spec["requires"] if not _have(r)]
    subprocess.run(["git", "add", "-A"], cwd=str(dest), check=True)
    subprocess.run(["git", "-c", "user.name=ratchet", "-c", "user.email=ratchet@localhost", "commit", "-q", "-m",
                    f"ratchet: walking skeleton ({stack})"], cwd=str(dest), check=True)
    result = {"dir": str(dest), "stack": stack, "checks": info["checks"], "products": info["products"],
              "missing_tools": missing, "proofs": [], "unverified": spec.get("unverified")}
    if prove and not missing:
        result["proofs"] = generate.prove_all(dest)
        h = harness.load(dest)
        from . import exercise

        result["exercises"] = [exercise.run(dest, h, ex["name"], tag="skeleton") for ex in exercise.all_exercises(h)]
    return result
